"""
Database models for HeatMapX authentication.

This module owns the single SQLAlchemy instance (`db`) that is initialized
against the Flask app in app.py, plus the `User` model backing the new
SQLite-based registration/login system.
"""
from datetime import datetime

from flask_sqlalchemy import SQLAlchemy
from werkzeug.security import generate_password_hash, check_password_hash

db = SQLAlchemy()


class User(db.Model):
    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(100), nullable=False)
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # --- Password helpers -------------------------------------------------
    def set_password(self, raw_password: str) -> None:
        """Hash and store the given plaintext password (never store it raw)."""
        self.password_hash = generate_password_hash(raw_password)

    def check_password(self, raw_password: str) -> bool:
        """Verify a plaintext password against the stored hash."""
        return check_password_hash(self.password_hash, raw_password)

    # --- Flask-Login required properties -----------------------------------
    # Flask-Login expects these on any object used as its "user"; implementing
    # them here avoids pulling in the UserMixin class so the model stays plain.
    @property
    def is_authenticated(self):
        return True

    @property
    def is_active(self):
        return True

    @property
    def is_anonymous(self):
        return False

    def get_id(self):
        return str(self.id)

    # --- Serialization -------------------------------------------------
    def to_dict(self):
        return {
            "id": self.id,
            "name": self.name,
            "email": self.email,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }
